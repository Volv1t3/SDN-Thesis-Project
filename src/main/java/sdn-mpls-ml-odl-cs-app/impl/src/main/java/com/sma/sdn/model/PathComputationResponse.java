package com.sma.sdn.model;

import java.util.List;

/**
 * <p>Represents the parsed status, path descriptions, and metric returned by an OpenDaylight path computation. The path computation service checks completion before translating the returned hops.</p>
 *
 * @param status operation or response status
 * @param pathDescriptions ordered path descriptions
 * @param computedTeMetric reported traffic-engineering metric
 */
public record PathComputationResponse(
        String status, /*status of the calculation, hopefully always completed*/
        List<PathHop> pathDescriptions, /*List of hops generated by the algorithm as path description objects*/
        int computedTeMetric /*Always 1 as we are not using this*/) {

    /**
     * <p>Determine whether the path response contains a completed result.</p>
     *
     * <p>The operation proceeds as follows:</p>
     * <ol>
     *   <li>Check that status equals {@code completed} ignoring case and that path descriptions are non-null and nonempty.</li>
     * </ol>
     *
     * @return true when both conditions hold
     */
    public boolean completed() {
        return "completed".equalsIgnoreCase(status) && pathDescriptions != null && !pathDescriptions.isEmpty();
    }
}
